const ASPIRATE = {
  'ब': 'भ', 'प': 'फ', 'त': 'थ', 'ट': 'ठ', 'ज': 'झ', 'च': 'छ', 'द': 'ध', 'ड': 'ढ', 'ड़': 'ढ़',
  'क': 'ख', 'ग': 'घ', 'र': 'रह', 'ल': 'लह', 'म': 'मह', 'न': 'नह',
};

function translitWord(w) {
  const ch = [...w];
  let out = '';
  const n = ch.length;
  for (let i = 0; i < n; i++) {
    const c = ch[i];
    const first = i === 0, last = i === n - 1;
    if (c === 'ھ') {
      // aspirate the consonant just written
      const prevKey = Object.keys(ASPIRATE).find(k => out.endsWith(k));
      if (prevKey) out = out.slice(0, out.length - prevKey.length) + ASPIRATE[prevKey];
      else out += 'ह';
      continue;
    }
    if (c === 'آ') { out += 'आ'; continue; }
    if (c === 'ا') { out += first ? 'अ' : 'ा'; continue; }
    if (c === 'ع') { out += first ? 'अ' : ''; continue; }
    if (c === 'و') {
      if (first) out += 'व';
      else if (ch[i - 1] === 'ا' || ch[i - 1] === 'آ') out += 'व';
      else out += 'ो';
      continue;
    }
    if (c === 'ی' || c === 'ي' || c === 'ى') {
      if (first || ch[i + 1] === 'ا' || ch[i + 1] === 'و') out += 'य';
      else if (ch[i - 1] === 'ا' || ch[i - 1] === 'آ' || ch[i - 1] === 'و') out += 'ई';
      else out += last ? 'ी' : 'ी';
      continue;
    }
    if (c === 'ے') { out += (ch[i - 1] === 'ا' || ch[i - 1] === 'و') ? 'ए' : 'े'; continue; }
    if (c === 'ئ') { out += 'इ'; continue; }
    if (c === 'ء' || c === 'ٔ') continue;
    if (c === 'ں') { out += 'ँ'; continue; }
    if ((c === 'ہ' || c === 'ه' || c === 'ة') && last && i > 0) { out += 'ा'; continue; }
    if (c === 'ّ') { // shadda: double the previous consonant
      const m = out.match(/([क-ह]़?)$/);
      if (m) out = out.slice(0, -m[1].length) + m[1] + '्' + m[1];
      continue;
    }
    if (CONS[c]) { out += CONS[c]; continue; }
    // diacritics we do not model, and anything else, pass through
    if (/[ً-ٰٟ]/.test(c)) continue;
    out += c;
  }
  return out;
}

export function toDevanagari(text) {
  const t = String(text || '').trim();
  if (!t) return t;
  if (WORDS[t]) return WORDS[t];
  return t.split(/(\s+)/).map(part => (/^\s+$/.test(part) ? part : (WORDS[part] || translitWord(part)))).join('');
}

